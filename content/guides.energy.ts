/**
 * Electricity-cost guides: the prose half of the calculators under /tools.
 *
 * Every table here is computed from `lib/energy/tariff.ts` at build time
 * rather than typed in, so a tariff update changes the tables, the
 * calculators and the short answers together. The prose quotes a handful of
 * the same figures; when the tariff moves, search this file for the old rate.
 */

const MARKET_HP = [1, 1.25, 1.5, 2, 2.5, 3, 3.5];

function marketSize(btu: number): number {
  const hp = btu / BTU_PER_HP;
  return MARKET_HP.find((size) => size >= hp - 0.1) ?? MARKET_HP[MARKET_HP.length - 1];
}

const AC_ROOMS: [number, number][] = [
  [9, 1],
  [12, 2],
  [15, 2],
  [18, 2],
  [20, 2],
  [25, 3],
  [30, 4],
  [35, 4],
  [40, 5],
];

const AC_SIZE_ROWS = AC_ROOMS.map(([area, people]) => {
  const btu = recommendedBtu(area, people);
  return [`${area} מ״ר, ${people} ${people === 1 ? "אדם" : "אנשים"}`, fmt(btu, 0), fmt(btu / BTU_PER_HP, 2), `${fmt(marketSize(btu))} כ״ס`];
});

/** Cost of an AC at `hp`, COP 3.5, average load 70%. */
function acCost(hp: number, hoursPerDay: number, days: number): number {
  return acElectricKw(hp * BTU_PER_HP, 3.5) * 0.7 * hoursPerDay * days * TARIFF_ILS;
}

const AC_COST_ROWS = MARKET_HP.slice(0, 6).map((hp) => [
  `${fmt(hp)} כ״ס (${fmt(hp * BTU_PER_HP, 0)} BTU)`,
  ils(acElectricKw(hp * BTU_PER_HP, 3.5) * TARIFF_ILS),
  ils(acCost(hp, 1, 1)),
  ils(acCost(hp, 8, 30)),
  ils(acCost(hp, 8, 120)),
]);

const FRIDGE_KWH = [200, 250, 300, 350, 400, 500, 600, 800];
const FRIDGE_ROWS = FRIDGE_KWH.map((kwh) => [
  `${fmt(kwh, 0)} קוט״ש`,
  ils((kwh / 12) * TARIFF_ILS),
  ils(kwh * TARIFF_ILS),
  ils(kwh * TARIFF_ILS * 12),
]);

const APPLIANCE_ROWS = Object.entries(APPLIANCE_PRESETS)
  .filter(([key]) => key !== "custom")
  .map(([, p]) => {
    const kwhMonth = (p.watts / 1000) * (p.duty / 100) * p.hours * p.days;
    const usage = `${fmt(p.hours, 2)} ש׳ × ${p.days} ימים${p.duty < 100 ? ` (${p.duty}% מהזמן)` : ""}`;
    return [p.label, `${fmt(p.watts, 0)} W`, ils((p.watts / 1000) * TARIFF_ILS), usage, ils(kwhMonth * TARIFF_ILS)];
  });

function boilerMinutes(liters: number, cold: number): number {
  const kwh = (liters * 4.186 * (55 - cold)) / 3600 / 0.95;
  return Math.ceil(((kwh / 2.5) * 60 - 1e-9) / 5) * 5;
}
function boilerCost(liters: number, cold: number): number {
  return ((liters * 4.186 * (55 - cold)) / 3600 / 0.95) * TARIFF_ILS;
}
function minutesHe(minutes: number): string {
  const h = Math.floor(minutes / 60);
  const m = minutes % 60;
  if (h === 0) return `${m} דק׳`;
  return m === 0 ? `${h}:00 ש׳` : `${h}:${String(m).padStart(2, "0")} ש׳`;
}
const BOILER_ROWS = [60, 80, 100, 120, 150, 200].map((liters) => [
  `${liters} ליטר`,
  `${minutesHe(boilerMinutes(liters, 15))} · ${ils(boilerCost(liters, 15))}`,
  `${minutesHe(boilerMinutes(liters, 20))} · ${ils(boilerCost(liters, 20))}`,
  `${minutesHe(boilerMinutes(liters, 25))} · ${ils(boilerCost(liters, 25))}`,
]);

